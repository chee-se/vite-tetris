// SRS（スーパーローテーションシステム）の壁蹴りの表。
// 出典: https://tetris.wiki/Super_Rotation_System の Wall Kick Data
//
// 回転してぶつかったら、表の候補を先頭から順に試し、最初にぶつからなかった位置に動かす。
// どの候補でもぶつかるなら回転しない。1 つ目の候補はどれも [0, 0]（その場で回す）。
//
// 出典の表は「y が上向きに正」だが、このプロジェクトは y = 0 が一番上で、下向きに正。
// そのため、出典の y の符号をすべて反転している（例: 出典の (-1, +1) → ここでは [-1, -1]）

// [dx, dy]。ミノの位置（x, y）に足す量
export type Kick = readonly [dx: number, dy: number]

// 「回転前の向き > 回転後の向き」。0 = 出現時、1 = 右回転 1 回（R）、2 = 2 回、3 = 左回転 1 回（L）
const ROTATION_CHANGE = [
  '0>1',
  '1>0',
  '1>2',
  '2>1',
  '2>3',
  '3>2',
  '3>0',
  '0>3',
] as const
export type RotationChange = (typeof ROTATION_CHANGE)[number]

export function isRotationChange(key: string): key is RotationChange {
  return (ROTATION_CHANGE as readonly string[]).includes(key)
}

// J, L, S, T, Z の表
// prettier-ignore
export const JLSTZ_KICKS = {
  '0>1': [[0, 0], [-1, 0], [-1, -1], [0, 2], [-1, 2]],
  '1>0': [[0, 0], [1, 0], [1, 1], [0, -2], [1, -2]],
  '1>2': [[0, 0], [1, 0], [1, 1], [0, -2], [1, -2]],
  '2>1': [[0, 0], [-1, 0], [-1, -1], [0, 2], [-1, 2]],
  '2>3': [[0, 0], [1, 0], [1, -1], [0, 2], [1, 2]],
  '3>2': [[0, 0], [-1, 0], [-1, 1], [0, -2], [-1, -2]],
  '3>0': [[0, 0], [-1, 0], [-1, 1], [0, -2], [-1, -2]],
  '0>3': [[0, 0], [1, 0], [1, -1], [0, 2], [1, 2]],
} as const satisfies Record<RotationChange, readonly Kick[]>

